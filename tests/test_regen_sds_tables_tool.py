"""
tools/regen_sds_tables.py regenerates the SDS jump statistics.

* The random walk is pinned: small runs for both partner draws and both
  step models give the radii the tool gave before its two rejection
  loops were bounded (the bound changed no draw).
* An end-to-end run at tiny N writes a table the runtime loader reads,
  in the shipped layout, with the provenance header.
* A rejection sampler that runs out of tries stops the run loudly,
  naming the ions and the sampler, instead of looping forever.
"""
import importlib.util
import sys
from pathlib import Path

import numpy as np
import pytest

from ion_gym.physics import sds

TOOL = Path(__file__).resolve().parents[1] / "tools" / "regen_sds_tables.py"

# _walk_rjump(6, 300, 10.0, flux, 123, distance) from the tool as it was
# before the loops were bounded (unbounded `while True` rejection).
PINNED = {
    (True, True): [40.087748166724936, 52.93007328757277,
                   112.23786186701915, 95.43628646770308,
                   29.801390442318805, 66.42609377012086],
    (True, False): [57.6548624229672, 79.42837975542969,
                    155.0883750530732, 101.56479916763881,
                    52.444254045228135, 67.56985785274266],
    (False, True): [85.06242902111335, 82.97333045166664,
                    146.8455632036199, 79.67933127651555,
                    78.4849210109187, 49.28872135683822],
    (False, False): [93.20960730054475, 90.8136235856313,
                     172.37479707544708, 76.09543263262208,
                     79.52020032197939, 50.8959089119236],
}


def _load(path, name):
    """Import a tool file as module `name`. It is registered in
    sys.modules first: numba loads a CACHED parallel kernel by importing
    its module by name, which fails ("No module named '<dynamic>'") for a
    module that exists only as an object."""
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def tool():
    return _load(TOOL, "regen_sds_tables")


@pytest.mark.parametrize("flux,distance", sorted(PINNED))
def test_the_walk_is_unchanged(tool, flux, distance):
    r = tool._walk_rjump(6, 300, 10.0, flux, 123, distance)
    assert np.allclose(r, PINNED[(flux, distance)], rtol=1e-12, atol=0)


def test_a_small_run_writes_a_table_the_runtime_reads(tool, tmp_path):
    assert tool.main(["--n-ions", "40", "--n-collisions", "200",
                      "--flux-weighted", "--out-dir", str(tmp_path),
                      "--tag", "t"]) == 0
    table = tmp_path / "sds_jump_icdf_t.dat"
    curves = sds.load_diffusion_statistics(table)
    assert curves.shape == (5, 1002)
    assert np.all(np.diff(curves, axis=1) >= 0)
    head = table.read_text(encoding="utf-8")[:600]
    assert "REGENERATED by tools/regen_sds_tables.py" in head
    assert "Appelhans" in head and "flux-weighted MB" in head
    assert np.load(tmp_path / "rjump_raw_t.npy").shape == (5, 40)


@pytest.mark.parametrize("flux", [True, False], ids=["partner", "sphere"])
def test_an_exhausted_sampler_stops_the_run_loudly(tmp_path, flux):
    src = TOOL.read_text(encoding="utf-8")
    assert src.count("MAX_REJECTION_TRIES = 10_000") == 1
    broken = tmp_path / "regen_zero_tries.py"
    broken.write_text(src.replace("MAX_REJECTION_TRIES = 10_000",
                                  "MAX_REJECTION_TRIES = 0"),
                      encoding="utf-8")
    mod = _load(broken, f"regen_zero_tries_{flux}")
    with pytest.raises(RuntimeError) as exc:
        mod._walk_rjump(4, 10, 10.0, flux, 1, True)
    msg = str(exc.value)
    assert "4 of 4 ions stopped" in msg
    assert ("4 flux-weighted partner draws" if flux
            else "4 sphere-direction draws") in msg
